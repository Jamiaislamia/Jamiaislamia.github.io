/* ── runtime: siteT(), siteBi() ──────────────────────────────────
   The dictionary above is a look-up table for JS-rendered strings only:
     • JS-rendered strings             → siteT() returns "বাংলা · English".
     • Structured data (title/titleEn) → siteBi() renders the pair.
   Authored HTML is never walked: applyBilingual() is a no-op shim, so no
   English block can be appended twice. */
(function () {
  /* The dictionary survives as the translation memory for strings that JS
     renders (status chips, buttons, toasts, empty states). Authored markup is
     NEVER walked any more: each slot carries exactly one language — see the
     language law at the top of site.css. */
  function dict() { return (window.SITE_I18N && window.SITE_I18N.en) || {}; }
  function hasBangla(s) { return /[\u0980-\u09FF]/.test(String(s == null ? '' : s)); }

  function englishOf(s) {
    var v = dict()[s];
    return (v && v !== s) ? v : null;
  }

  function escapeHtml(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  /* ── siteT: "বাংলা · English" for a JS-rendered UI string ── */
  function siteT(str) {
    if (str == null) return '';
    var s = String(str);
    if (!hasBangla(s)) return s;
    var en = englishOf(s);
    if (!en) return s;
    if (s.indexOf(' · ' + en) !== -1) return s;      /* already paired */
    return s + ' · ' + en;
  }

  /* ── siteBi: "Bangla<span class='bi-en'>English</span>" as SAFE HTML ── */
  function siteBi(bn, en) {
    var a = String(bn == null ? '' : bn);
    var b = String(en == null ? '' : en);
    if (!b || b === a) return escapeHtml(a);
    if (!hasBangla(a)) return escapeHtml(a + ' · ' + b);
    return escapeHtml(a) + '<span class="bi-en" lang="en">' + escapeHtml(b) + '</span>';
  }

  /* ── compatibility shims: one fixed theme, one fixed language mode ──
     applyBilingual() is intentionally a no-op: bilingual copy is authored in
     the markup (English labels + one orientation line per section), so there
     is nothing left to inject and nothing can be injected twice. */
  window.siteT = siteT;
  window.siteBi = siteBi;
  window.siteEn = englishOf;
  window.siteLang = function () { return 'bi'; };
  window.siteTheme = function () { return 'dusk'; };
  window.siteApplyLang = function () { };
  window.siteApplyBilingual = function () { };
  window.siteSetLang = function () { };
  window.siteSetTheme = function () { };
  window.siteToggleTheme = function () { };
  window.siteToggleLang = function () { };
})();
